use super::*;
use serde::de::DeserializeOwned;

fn argument<T: DeserializeOwned>(args: &Value, key: &str) -> Res<T> {
    serde_json::from_value(args[key].clone()).map_err(|err| format!("{key}: {err}"))
}

pub(super) async fn call(state: &AppState, method: &str, args: &Value) -> Res<Value> {
    Ok(match method {
        "add_subscription" => json!(add_subscription(state, argument(args, "input")?).await?),
        "cached_show" => json!(cached_show(state, argument(args, "input")?)?),
        "preview_show" => json!(preview_show(state, argument(args, "input")?).await?),
        "refresh_show" => json!(refresh_show(state, argument(args, "id")?).await?),
        "refresh_all" => json!(refresh_all(state).await?),
        "list_shows" => json!(list_shows(state)?),
        "list_episodes" => json!(list_episodes(state, argument(args, "showId")?, argument(args, "limit")?)?),
        "search_show" => json!(search_show(state, argument(args, "showId")?, argument(args, "query")?).await?),
        "recent_episodes" => json!(recent_episodes(state)?),
        "get_episode" => json!(get_episode(state, argument(args, "id")?)?),
        "remove_show" => json!(remove_show(state, argument(args, "id")?)?),
        "set_progress" => json!(set_progress(state, argument(args, "id")?, argument(args, "seconds")?)?),
        "search_podcasts" => json!(search_podcasts(argument(args, "term")?, argument(args, "country")?).await?),
        "load_transcript" => json!(load_transcript(state, argument(args, "episodeId")?)?),
        "youtube_tracks" => json!(youtube_tracks(state, argument(args, "episodeId")?).await?),
        "use_youtube_track" => json!(use_youtube_track(state, argument(args, "episodeId")?, argument(args, "language")?, argument(args, "auto")?).await?),
        "fetch_official_transcript" => json!(fetch_official_transcript(state, argument(args, "episodeId")?).await?),
        "qiaomu_detail" => json!(qiaomu_detail(state, argument(args, "episodeId")?).await?),
        "save_image" => json!(save_image(argument(args, "name")?, argument(args, "base64")?)?),
        "list_models" => json!(list_models(argument(args, "provider")?).await?),
        "tts_speak" => json!(tts_speak(argument(args, "text")?, argument(args, "voice")?, argument(args, "resource")?).await?),
        "refresh_config" => json!(refresh_config(state).await?),
        "youtube_stream" => json!(youtube_stream(AppHandle, state, argument(args, "videoId")?, argument(args, "mode")?, argument(args, "fresh")?).await?),
        "prepare_youtube" => json!(prepare_youtube(state).await?),
        "download_episode" => json!(download_episode(AppHandle, state, argument(args, "episodeId")?).await?),
        "list_downloads" => json!(list_downloads(state)),
        "delete_download" => json!(delete_download(state, argument(args, "episodeId")?)?),
        "clear_downloads" => json!(clear_downloads(state)?),
        "full_notes" => json!(full_notes(state, argument(args, "episodeId")?).await?),
        "storage_info" => json!(storage_info(state)),
        "open_data_folder" => json!(open_data_folder(state, argument(args, "kind")?)?),
        "reveal_download" => json!(reveal_download(state, argument(args, "episodeId")?)?),
        "clear_temp" => json!(clear_temp(state)?),
        "shared_transcript" => json!(shared_transcript(state, argument(args, "episodeId")?).await?),
        "shared_exists" => json!(shared_exists(state, argument(args, "episodeIds")?).await?),
        "transcribe" => json!(transcribe(AppHandle, state, argument(args, "episodeId")?, argument(args, "model")?, argument(args, "language")?, argument(args, "cloud")?).await?),
        "share_translation" => json!(share_translation(state, argument(args, "episodeId")?, argument(args, "engine")?, argument(args, "model")?).await?),
        "shared_guide" => json!(shared_guide(state, argument(args, "episodeId")?).await?),
        "share_guide" => json!(share_guide(state, argument(args, "episodeId")?, argument(args, "text")?, argument(args, "model")?).await?),
        "cancel_job" => json!(cancel_job(state, argument(args, "id")?)),
        "asr_models" => json!(asr_models(state).await?),
        "download_model" => json!(download_model(AppHandle, state, argument(args, "id")?, argument(args, "mirrorFirst")?).await?),
        "log_listen" => json!(log_listen(state, argument(args, "episodeId")?, argument(args, "showId")?, argument(args, "seconds")?, argument(args, "translated")?)?),
        "listening_stats" => json!(listening_stats(state, argument(args, "since")?)?),
        "asr_elsewhere" => json!(asr_elsewhere()),
        "rescan_models" => json!(rescan_models()),
        "delete_model" => json!(delete_model(state, argument(args, "id")?)?),
        "get_blob" => json!(get_blob(state, argument(args, "episodeId")?, argument(args, "kind")?)?),
        "set_blob" => json!(set_blob(state, argument(args, "episodeId")?, argument(args, "kind")?, argument(args, "data")?)?),
        "get_settings" => json!(get_settings(state)?),
        "set_settings" => json!(set_settings(state, argument(args, "settings")?)?),
        "set_api_key" => json!(set_api_key(argument(args, "provider")?, argument(args, "key")?)?),
        "has_api_key" => json!(has_api_key(argument(args, "provider")?)),
        "llm_chat" => json!(llm_chat(AppHandle, state, argument(args, "requestId")?, argument(args, "provider")?, argument(args, "system")?, argument(args, "messages")?, argument(args, "maxTokens")?, argument(args, "jsonMode")?).await?),
        "youtube_subscriptions" => json!(youtube_subscriptions(state, argument(args, "browser")?).await?),
        "open_privacy_settings" => json!(open_privacy_settings()?),
        "export_opml" => json!(export_opml(state)?),
        "local_agents" => json!(local_agents().await),
        "probe_agent" => json!(probe_agent(argument(args, "kind")?).await?),
        "agent_models" => json!(agent_models(argument(args, "kind")?).await?),
        "warm_agent" => json!(warm_agent(argument(args, "kind")?).await),
        "translate_texts" => json!(translate_texts(state, argument(args, "texts")?, argument(args, "target")?).await?),
        _ => return Err(format!("Unknown SubCast command: {method}")),
    })
}
